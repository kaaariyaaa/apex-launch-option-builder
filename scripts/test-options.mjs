import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { inputType, parseRankings, valid, renderOption } from '../src/lib/options.ts';

const options = JSON.parse(await readFile(new URL('../public/data/registrations.json', import.meta.url)));
const get = (name) => options.find((option) => option.name === name);
assert.equal(renderOption(get('+fps_max'), '200'), '+fps_max 200');
assert.equal(valid('200', get('+fps_max')), true);
assert.equal(valid('NaN', get('+fps_max')), false);
assert.equal(valid('', get('+fps_max')), false);
assert.equal(valid('0.5', get('+cl_is_softened_locale')), false);
assert.equal(valid('0', get('+cl_is_softened_locale')), true);
assert.equal(renderOption(get('-dev'), ''), '-dev');
assert.equal(renderOption(get('-affinity='), '0xff'), '-affinity=0xff');
assert.equal(renderOption(get('+exec'), 'my config.cfg'), '+exec "my config.cfg"');
assert.equal(valid('bad\n+exec bad', get('+exec')), false);
assert.equal(valid('a"b', get('+exec')), false);
for (const value of ['$()', '`id`', '&', 'x&y', '|', '<', '>', ';', "'", '%PATH%', '!var!', '^']) assert.equal(valid(value, get('+exec')), false, `${value} must be rejected`);
assert.equal(valid('my config.cfg', get('+exec')), true);
const speechPath = get('+speechtotext_path');
assert.equal(valid(speechPath.default, speechPath), true);
assert.equal(renderOption(speechPath, speechPath.default), `+speechtotext_path "${speechPath.default}"`);
assert.equal(inputType(get('-forcedAffinity')), 'text');
assert.equal(valid('0xff', get('-forcedAffinity')), true);
assert.deepEqual(parseRankings('{"rankings":[{"id":"fps","users":2},null,{"id":3,"users":1}]}'), [{ id: 'fps', users: 2 }]);
assert.deepEqual(parseRankings('{'), []);
assert.equal(valid('', get('+break')), true);
assert.equal(renderOption(get('+break'), ''), '+break');
const emptyString = options.find((option) => option.value_kind.includes('空値可'));
assert.equal(valid('', emptyString), true);
assert.equal(renderOption(emptyString, ''), `${emptyString.name} ""`);
console.log('Command generation and value validation checks passed.');
